export type Dict = (typeof dict)[Lang]
export type I18nKey = keyof Dict

/** Current UI language (also used by print bridge outside React). */
export function activeLang(): Lang {
  try {
    return localStorage.getItem('mesa-lang') === 'ar' ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}

export function messages(lang: Lang = activeLang()): Dict {
  return dict[lang]
}

